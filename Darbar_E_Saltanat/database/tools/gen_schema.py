#!/usr/bin/env python3
"""Generate MySQL schema, SQLite schema and the sync entity registry from schema_spec.py."""
import json, re, sys
from pathlib import Path
from schema_spec import TABLES

ROOT = Path(__file__).resolve().parents[2]

TYPE_MYSQL = {
    "text": "TEXT", "int": "INT", "bigint": "BIGINT", "bool": "TINYINT(1)",
    "money": "DECIMAL(12,2)", "qty": "DECIMAL(14,3)", "pct": "DECIMAL(5,2)",
    "dt": "DATETIME(3)", "date": "DATE", "time": "TIME", "json": "JSON",
}
TYPE_SQLITE = {
    "text": "TEXT", "int": "INTEGER", "bigint": "INTEGER", "bool": "INTEGER",
    "money": "TEXT", "qty": "TEXT", "pct": "TEXT",   # decimals stored as exact TEXT
    "dt": "TEXT", "date": "TEXT", "time": "TEXT", "json": "TEXT",
}


def parse(table):
    cols, fks, idx, uniq = [], [], [], []
    for raw in table["cols"].splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("@fk"):
            p = line.split()
            fks.append(dict(name=p[1], ref=p[2], null=("null" in p[3:])))
        elif line.startswith("@idx"):
            idx.append(line.split()[1].split(","))
        elif line.startswith("@uniq"):
            uniq.append(line.split()[1].split(","))
        else:
            p = line.split()
            c = dict(name=p[0], type=p[1], null=False, unique=False, default=None)
            for f in p[2:]:
                if f == "null": c["null"] = True
                elif f == "unique": c["unique"] = True
                elif f.startswith("="): c["default"] = f[1:]
            cols.append(c)
    return cols, fks, idx, uniq


def enum_values(t):
    return t[5:-1].split("|")


def mysql_type(t):
    if t.startswith("enum("):
        return "ENUM(" + ",".join("'%s'" % v for v in enum_values(t)) + ")"
    m = re.fullmatch(r"(s|char)(\d+)", t)
    if m:
        return ("VARCHAR(%s)" if m.group(1) == "s" else "CHAR(%s)") % m.group(2)
    return TYPE_MYSQL[t]


def sqlite_type(t):
    if re.fullmatch(r"(s|char)\d+", t) or t.startswith("enum("):
        return "TEXT"
    return TYPE_SQLITE[t]


def default_sql(c, dialect):
    d = c["default"]
    if d is None:
        return ""
    if d.startswith("'"):
        return f" DEFAULT {d}"
    if c["type"].startswith("enum(") or re.fullmatch(r"(s|char)\d+", c["type"]) or c["type"] == "text":
        return f" DEFAULT '{d}'"
    return f" DEFAULT {d}"


def flags_of(t):
    return t["flags"]


def build():
    parsed = {t["name"]: parse(t) for t in TABLES}
    names = [t["name"] for t in TABLES]
    # dependency check (self references allowed)
    seen = set()
    for t in TABLES:
        cols, fks, _, _ = parsed[t["name"]]
        for fk in fks:
            if fk["ref"] != t["name"] and fk["ref"] not in seen and fk["ref"] in names:
                # forward reference: orders -> coupons etc. are ordered; report loudly
                if fk["ref"] not in seen:
                    sys.exit(f"ORDER ERROR: {t['name']} references {fk['ref']} before it is defined")
        seen.add(t["name"])
    return parsed


# ------------------------------------------------------------------ MySQL
def mysql_ddl(parsed):
    out = ["""-- ============================================================================
-- Darbar_E_Saltanat — MySQL 8 schema (GENERATED by database/tools/gen_schema.py)
-- Do not edit by hand: change database/tools/schema_spec.py and regenerate.
--
-- Conventions
--   * InnoDB, utf8mb4_unicode_ci
--   * `id`  BIGINT UNSIGNED AUTO_INCREMENT = internal key (never leaves the server)
--   * `uuid` CHAR(36) = public/global identifier used by the API and by desktop sync
--   * money DECIMAL(12,2); quantities DECIMAL(14,3); all timestamps UTC, DATETIME(3)
--   * soft deletes via `deleted_at`; syncable rows carry sync_version/device_id/sync_status
-- ============================================================================
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
"""]
    for t in TABLES:
        name = t["name"]; fl = t["flags"]
        cols, fks, idx, uniq = parsed[name]
        syncable = "sync" in fl
        lines = ["  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT",
                 "  `uuid` CHAR(36) NOT NULL"]
        if syncable and name != "branches":
            nullable = "global" in fl
            lines.append("  `branch_id` BIGINT UNSIGNED %s" % ("NULL" if nullable else "NOT NULL"))
        for fk in fks:
            lines.append("  `%s_id` BIGINT UNSIGNED %s" % (fk["name"], "NULL" if fk["null"] else "NOT NULL"))
        for c in cols:
            nn = "NULL" if c["null"] else "NOT NULL"
            lines.append("  `%s` %s %s%s" % (c["name"], mysql_type(c["type"]), nn, default_sql(c, "mysql")))
        lines.append("  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)")
        lines.append("  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)")
        if syncable:
            lines.append("  `deleted_at` DATETIME(3) NULL")
            lines.append("  `sync_version` INT UNSIGNED NOT NULL DEFAULT 1")
            lines.append("  `device_id` CHAR(36) NULL COMMENT 'uuid of the device that last wrote the row'")
            lines.append("  `sync_status` ENUM('SYNCED','CONFLICT') NOT NULL DEFAULT 'SYNCED'")
        lines.append("  PRIMARY KEY (`id`)")
        lines.append("  UNIQUE KEY `uq_%s_uuid` (`uuid`)" % name)
        for c in cols:
            if c["unique"]:
                lines.append("  UNIQUE KEY `uq_%s_%s` (`%s`)" % (name, c["name"], c["name"]))

        def colname(n):
            if any(f["name"] == n for f in fks): return n + "_id"
            if n == "branch": return "branch_id"
            return n
        for u in uniq:
            cn = [colname(x) for x in u]
            lines.append("  UNIQUE KEY `uq_%s_%s` (%s)" % (name, "_".join(cn), ",".join("`%s`" % x for x in cn)))
        for i in idx:
            cn = [colname(x) for x in i]
            lines.append("  KEY `ix_%s_%s` (%s)" % (name, "_".join(cn), ",".join("`%s`" % x for x in cn)))
        if syncable:
            lines.append("  KEY `ix_%s_updated_at` (`updated_at`)" % name)
            lines.append("  KEY `ix_%s_sync` (`sync_status`,`device_id`)" % name)
            lines.append("  KEY `ix_%s_branch_updated` (`branch_id`,`updated_at`)" % name)
        else:
            lines.append("  KEY `ix_%s_updated_at` (`updated_at`)" % name)
        for fk in fks:
            lines.append("  CONSTRAINT `fk_%s_%s` FOREIGN KEY (`%s_id`) REFERENCES `%s` (`id`)" % (name, fk["name"], fk["name"], fk["ref"]))
        if syncable and name != "branches":
            lines.append("  CONSTRAINT `fk_%s_branch` FOREIGN KEY (`branch_id`) REFERENCES `branches` (`id`)" % name)
        cm = (" COMMENT='%s'" % t["comment"].replace("'", "''")) if t["comment"] else ""
        out.append("CREATE TABLE `%s` (\n%s\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci%s;\n" % (name, ",\n".join(lines), cm))
    out.append("""CREATE TABLE `schema_migrations` (
  `version` VARCHAR(100) NOT NULL,
  `applied_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`version`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;
""")
    return "\n".join(out)



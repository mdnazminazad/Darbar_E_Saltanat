def sqlite_ddl(parsed):
    out = ["""-- ============================================================================
-- Darbar_E_Saltanat — Desktop SQLite schema (GENERATED by database/tools/gen_schema.py)
-- Local offline source of truth. PRAGMAs are applied by the app on every connection:
--   journal_mode=WAL; foreign_keys=ON; synchronous=NORMAL; busy_timeout=5000
--
--   * `id` INTEGER = LOCAL-ONLY rowid. Never sent to the server and never used as a global ID.
--   * `uuid` TEXT = global identifier. All relations reference parent `uuid`, as <name>_uuid.
--     (`branch_uuid` is the SQLite/wire name of the logical `branch_id` column.)
--   * Decimals (money/qty/pct) are stored as exact TEXT; timestamps are ISO-8601 UTC TEXT.
-- ============================================================================
"""]
    for t in TABLES:
        name = t["name"]; fl = t["flags"]
        if "server" in fl:
            continue
        cols, fks, idx, uniq = parsed[name]
        lines = ["  id INTEGER PRIMARY KEY AUTOINCREMENT", "  uuid TEXT NOT NULL UNIQUE"]
        if name != "branches":
            lines.append("  branch_uuid TEXT %s" % ("NULL" if "global" in fl else "NOT NULL"))
        for fk in fks:
            lines.append("  %s_uuid TEXT %s" % (fk["name"], "NULL" if fk["null"] else "NOT NULL"))
        checks = []
        for c in cols:
            nn = "NULL" if c["null"] else "NOT NULL"
            extra = " UNIQUE" if c["unique"] else ""
            lines.append("  %s %s %s%s%s" % (c["name"], sqlite_type(c["type"]), nn, default_sql(c, "sqlite"), extra))
            if c["type"].startswith("enum("):
                checks.append("  CHECK (%s IN (%s))" % (c["name"], ",".join("'%s'" % v for v in enum_values(c["type"]))) if not c["null"] else
                              "  CHECK (%s IS NULL OR %s IN (%s))" % (c["name"], c["name"], ",".join("'%s'" % v for v in enum_values(c["type"]))))
            if c["type"] == "bool":
                checks.append("  CHECK (%s IN (0,1))" % c["name"])
        lines += ["  created_at TEXT NOT NULL", "  updated_at TEXT NOT NULL", "  deleted_at TEXT NULL",
                  "  sync_version INTEGER NOT NULL DEFAULT 0",
                  "  device_id TEXT NULL",
                  "  sync_status TEXT NOT NULL DEFAULT 'PENDING' CHECK (sync_status IN ('PENDING','SYNCED','CONFLICT','FAILED'))"]
        cons = []
        for fk in fks:
            cons.append("  FOREIGN KEY (%s_uuid) REFERENCES %s(uuid)" % (fk["name"], fk["ref"]))
        if name != "branches":
            cons.append("  FOREIGN KEY (branch_uuid) REFERENCES branches(uuid)")
        body = ",\n".join(lines + checks + cons)
        out.append("CREATE TABLE %s (\n%s\n);" % (name, body))

        def colname(n):
            if any(f["name"] == n for f in fks): return n + "_uuid"
            if n == "branch": return "branch_uuid"
            return n
        for u in uniq:
            cn = [colname(x) for x in u]
            out.append("CREATE UNIQUE INDEX uq_%s_%s ON %s (%s);" % (name, "_".join(cn), name, ", ".join(cn)))
        for i in idx:
            cn = [colname(x) for x in i]
            out.append("CREATE INDEX ix_%s_%s ON %s (%s);" % (name, "_".join(cn), name, ", ".join(cn)))
        out.append("CREATE INDEX ix_%s_sync ON %s (sync_status, updated_at);" % (name, name))
        out.append("")
    out.append(SQLITE_EXTRA)
    return "\n".join(out)


# ------------------------------------------------------------------ registry
def registry(parsed):
    reg = {}
    for t in TABLES:
        name = t["name"]; fl = t["flags"]
        if "sync" not in fl:
            continue
        cols, fks, _, _ = parsed[name]
        reg[name] = dict(
            table=name,
            global_scope="global" in fl,
            append_only="append" in fl,
            financial="fin" in fl,
            has_branch=(name != "branches"),
            fks=[dict(name=f["name"], column=f["name"] + "_id", uuid_field=f["name"] + "_uuid", ref=f["ref"], nullable=f["null"]) for f in fks],
            columns=[dict(name=c["name"], type=("enum" if c["type"].startswith("enum(") else c["type"]),
                          nullable=c["null"], unique=c["unique"],
                          **({"values": enum_values(c["type"])} if c["type"].startswith("enum(") else {}),
                          **({"default": c["default"].strip("'")} if c["default"] is not None else {})) for c in cols],
        )
    return reg


def main():
    parsed = build()
    (ROOT / "database" / "mysql-schema.sql").write_text(mysql_ddl(parsed), encoding="utf-8")
    (ROOT / "database" / "sqlite-schema.sql").write_text(sqlite_ddl(parsed), encoding="utf-8")
    regdir = ROOT / "web" / "server" / "src" / "sync"
    regdir.mkdir(parents=True, exist_ok=True)
    (regdir / "entityRegistry.json").write_text(json.dumps(registry(parsed), indent=2), encoding="utf-8")
    print("generated", len(TABLES), "tables")


if __name__ == "__main__":
    main()
